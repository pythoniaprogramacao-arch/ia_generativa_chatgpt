#operações simples
a = 10
b = 3

print("Soma: ",a + b)
print("Subtração: ",a - b)
print("Multiplicação: ",a * b)
print("Divisão float: ",a / b)
print("Divisão Inteira: ",a // b)
print("Exponênciação: ",a ** b)

c = a // b
print("Verificando o valor c como float: ", float(c))

